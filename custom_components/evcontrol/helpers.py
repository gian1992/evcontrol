"""Helper functions for EV Control calculations."""
import logging
from typing import Optional, Tuple

_LOGGER = logging.getLogger(__name__)

# AC Level 2 wall-to-battery charging efficiency.
# Typical OBC (on-board charger) efficiency: 90-95%.
# Using 0.90 (conservative) so the system always starts earlier and never runs late.
# Increase toward 0.95 if your car charges very efficiently and starts too early.
CHARGING_EFFICIENCY = 0.90

POWER_MODES = {
    "eco": "Eco",
    "normal": "Normal",
    "power": "Power",
}


def convert_power_to_unit(value: float, from_unit: str, to_unit: str) -> float:
    """Convert power value between units (W, kW, MW)."""
    units = {"W": 1, "kW": 1000, "MW": 1000000}
    
    if from_unit not in units or to_unit not in units:
        _LOGGER.warning(f"Unknown unit conversion: {from_unit} to {to_unit}")
        return value
    
    # Convert to Watts first, then to target unit
    watts = value * units[from_unit]
    return watts / units[to_unit]


def power_to_current(power_watts: float, voltage: float) -> float:
    """Convert power (W) to current (A). Round down for safety."""
    if voltage <= 0:
        _LOGGER.error(f"Invalid voltage: {voltage}")
        return 0.0
    
    current = power_watts / voltage
    return int(current)  # Round down for safety


def power_to_current_float(power_watts: float, voltage: float) -> float:
    """Convert power (W) to current (A) without rounding."""
    if voltage <= 0:
        _LOGGER.error(f"Invalid voltage: {voltage}")
        return 0.0
    
    return power_watts / voltage


def current_to_power(current_amps: float, voltage: float) -> float:
    """Convert current (A) to power (W)."""
    return current_amps * voltage


def calculate_excess_after_battery(
    surplus: float,
    battery_power: float,
    battery_soc: float,
    actual_battery_charge_w: Optional[float] = None,
) -> float:
    """
    Calculate excess power after battery allocation.

    Used in AUTO/AUTO-ECO modes to determine available solar power for EV after battery gets priority.

    Logic:
    - If battery is full (>= 98%), give all surplus to EV (no battery power deduction)
    - If actual_battery_charge_w is provided (from sensor), use that exact value
    - Otherwise: cap battery allocation at 1000W (conservative estimate to avoid over-reserving)

    Args:
        surplus: Current surplus power after house consumption (W)
        battery_power: Available battery charging power from config (W)
        battery_soc: Current battery SOC (%)
        actual_battery_charge_w: Actual measured battery charge power (W, positive=charging).
                                  If provided, used instead of estimate. None if no sensor configured.

    Returns:
        Excess power available for EV after battery takes its share (W)
    """
    if battery_soc >= 98:
        # Battery is full: don't subtract battery power, use all surplus for EV
        return surplus
    elif surplus > 0 and (battery_power or 0) > 0:
        if actual_battery_charge_w is not None and actual_battery_charge_w > 0:
            # Use actual measured battery charge power — accurate, no over-reservation
            return max(0, surplus - actual_battery_charge_w)
        else:
            # Estimate: cap at 1000W (reduced from 1500W to avoid sending surplus to grid)
            reduced_battery_allocation = min(battery_power, 1000)
            return max(0, surplus - reduced_battery_allocation)
    else:
        # No solar or battery not charging: use normal allocation
        return max(0, surplus - (battery_power or 0))


def calculate_surplus(
    pv_power: float,
    house_consumption: float,
    ev_power: Optional[float] = None,
    consumption_includes_ev: bool = False,
) -> float:
    """
    Calculate surplus power (power sold to grid or available for EV charging).
    
    surplus = PV - House_consumption
    
    Args:
        pv_power: Power generated by PV (W)
        house_consumption: House consumption (W) - MUST be already adjusted for EV if needed
        ev_power: Not used - kept for backward compatibility
        consumption_includes_ev: Not used - kept for backward compatibility
    
    Returns:
        Surplus power in Watts (positive = available for EV or grid, negative = need from grid)
    """
    # Coordinator already handles EV subtraction from house_consumption
    # So just use house_consumption as-is
    surplus = pv_power - house_consumption
    
    _LOGGER.debug(
        f"Surplus calculation: PV={pv_power}W - Consumption={house_consumption}W = {surplus}W"
    )
    
    return surplus


def get_available_battery_power(
    battery_soc: float,
    battery_min_soc: float,
    battery_max_drain_power: float,
) -> float:
    """
    Get available power from battery for charging the EV.
    
    Args:
        battery_soc: Current battery state of charge (%)
        battery_min_soc: Minimum SOC threshold (%)
        battery_max_drain_power: Maximum drain power from battery (W)
    
    Returns:
        Available power in Watts (0 if SOC below threshold)
    """
    if battery_soc <= battery_min_soc:
        _LOGGER.debug(
            f"Battery SOC {battery_soc}% is at or below min {battery_min_soc}%"
        )
        return 0.0
    
    _LOGGER.debug(
        f"Battery available: {battery_max_drain_power}W (SOC {battery_soc}% > min {battery_min_soc}%)"
    )
    
    return battery_max_drain_power


# The reserve a supply keeps free for loads that start unannounced. A quarter
# of the supply is the compromise: enough to matter on a small contract,
# capped at roughly a water heater on a large one, because past that the
# reserve is protecting against nothing while costing the car real current.
GRID_MARGIN_FRACTION = 0.25
GRID_MARGIN_MIN_W = 300.0
GRID_MARGIN_MAX_W = 1500.0


def validate_control(user_input: dict) -> Optional[str]:
    """Reject a reserve that leaves the charger nothing to run on.

    A margin larger than the supply can spare is not a conservative setting, it
    is an off switch: the cap collapses below the charger's minimum and the car
    never charges from the grid again. Caught here, where someone is present to
    fix it, rather than discovered over a silent night.
    """
    volts = float(user_input.get("grid_voltage", 230) or 230)
    limit_w = float(user_input.get("grid_max_current_amps", 32) or 32) * volts
    margin_w = float(user_input.get("grid_safety_margin_w", 0) or 0)
    # 6 A is the lowest minimum any charger here has, and 300 W stands in for a
    # house that is never quite at zero.
    if limit_w - margin_w < 6.0 * volts + 300.0:
        return "margin_too_large"
    return None


def default_grid_margin_w(grid_limit_w: float) -> float:
    """A reserve that scales with the supply, because a fixed one cannot.

    The reserve has to be big enough to absorb an appliance starting unannounced,
    and small enough to leave the charger something to work with. Those pull in
    opposite directions and the balance moves with the size of the supply:

      * 6 kW: 1500 W, the size of a water heater, and 4.5 kW still left over.
      * 3 kW: 1500 W would leave 1500 W for house and car together -- under the
        1380 W a charger needs at its 6 A minimum as soon as the house draws
        anything at all. The car would never charge from the grid, and nothing
        would say why.

    So a quarter of the supply, floored at 300 W and capped at 1500 W. On a 3 kW
    contract that is 750 W, which leaves roughly 8 A for the car with a quiet
    house; on anything 6 kW or larger it settles at a water heater's worth.

    This is only the default. The value is a plain setting and a user who knows
    their own loads should change it.
    """
    return min(GRID_MARGIN_MAX_W, max(GRID_MARGIN_MIN_W,
                                     GRID_MARGIN_FRACTION * grid_limit_w))


def grid_import_cap_amps(
    grid_limit_w: float,
    margin_w: float,
    house_w: float,
    pv_w: float,
    voltage: float,
    charger_min_a: float,
    battery_signed_w: float = 0.0,
    battery_available_w: float = 0.0,
) -> Tuple[float, float]:
    """Highest current the car may draw without pushing imports past budget.

    The budget is on *imported* power, not on what the house draws: only what the
    meter sees counts, so PV and the home battery both widen it.

    The home battery counts twice over, and neither is double counting:

      * Power going **into** it is not a competing load. A hybrid inverter
        charges the battery from what is left after the loads, so a car that
        asks for those watts simply gets them and the battery charges slower.
        Subtracting them -- which this function did at first -- throws away real
        headroom for no reason.
      * Power it can give **out** is supply the meter never sees. Above its SOC
        floor the battery can cover part of the car, and the caller passes that
        capability in `battery_available_w`.

    So a battery charging at 1.5 kW that can also discharge 2.5 kW is worth
    4 kW of headroom: stopping the charge frees the first, discharging adds the
    second.

    This leans on the battery doing what it is configured to say it can. If it
    does not, imports rise and the next cycle -- 20 seconds later -- cuts the
    car back. That is the same exposure as any load starting unannounced, and
    `margin_w` is what covers it: head deliberately left unused, sized for the
    largest load that can start without warning, because no control loop reacts
    before a water heater does.

    Returns (cap_amps, headroom_watts). The cap is floored to a whole amp, and
    collapses to zero below the charger's minimum: there is no point closing a
    contactor on a current the car will ignore.

    Args:
        battery_signed_w: measured now; positive = charging, negative =
            discharging. Only the charging side is read, as headroom to reclaim.
        battery_available_w: what the battery may supply, already gated by its
            SOC floor by the caller (see `get_available_battery_power`).
    """
    # Only the charging side: a battery already discharging is supplying some of
    # `battery_available_w` rather than adding to it.
    battery_headroom_w = max(0.0, battery_signed_w) + max(0.0, battery_available_w)
    headroom_w = grid_limit_w - margin_w - house_w + pv_w + battery_headroom_w
    if headroom_w <= 0 or voltage <= 0:
        return 0.0, max(0.0, headroom_w)
    cap = float(int(headroom_w / voltage))
    if cap < charger_min_a:
        # Not a small allowance, none: a contactor closed on 4 A is a
        # contactor cycle spent on a current the car will refuse.
        cap = 0.0
    return cap, headroom_w


def calculate_available_current(
    surplus: float,
    battery_power: float,
    grid_max_power: float,
    battery_soc: float,
    battery_start_charge_soc: float,
    voltage: float,
    charger_min_current: float,
    charger_max_current: float,
    mode: str,
    battery_min_soc: float = 20.0,
    house_consumption: float = 0.0,
    safety_margin_watts: float = 500.0,
    battery_reservation_power: float = 500.0,
    ev_soc: Optional[float] = None,
    ev_battery_capacity_kwh: Optional[float] = None,
    seconds_until_auto_target: Optional[int] = None,
    automatic_charge_current: float = 15.0,
    auto_phase1_soc_threshold: float = 50.0,
    ev_charging_speed_percent_per_hour: float = 0.0,
    auto_timer_active: bool = False,
    auto_last_state: Optional[str] = None,
    actual_battery_charge_w: Optional[float] = None,
    target_soc: float = 100.0,
    charger_floor_current: Optional[float] = None,
    now_hour: Optional[float] = None,
    band_start_hour: Optional[float] = None,
    band_end_hour: Optional[float] = None,
) -> Tuple[float, str]:
    """
    Calculate available current for EV charging based on mode.
    
    Args:
        surplus: Surplus power from solar (W)
        battery_power: Available battery power (W)
        grid_max_power: Maximum power allowed from grid (kW)
        battery_soc: Current battery SOC (%)
        battery_start_charge_soc: SOC threshold to start using battery (%)
        voltage: Current voltage (V)
        charger_min_current: Minimum current to maintain charge (A)
        charger_max_current: Maximum charger current (A)
        mode: Charging mode ("eco", "normal", "power", "auto", "auto-eco")
        battery_min_soc: Minimum SOC threshold (%)
        house_consumption: Actual house consumption (W) - used to calculate grid availability
        safety_margin_watts: Safety margin to keep from grid limit (W), default 500W
        battery_reservation_power: Power to reserve for battery charging in Normal mode when SOC < 95% (W)
        ev_soc: EV battery State of Charge (%), required for AUTO/AUTO-ECO modes
        ev_battery_capacity_kwh: EV battery capacity in kWh, required for AUTO/AUTO-ECO modes
        seconds_until_auto_target: Seconds until next charging target time, required for AUTO/AUTO-ECO modes
        automatic_charge_current: Base charging current for AUTO modes (A)
        target_soc: SOC the deadline asks for (%), default 100. Set per weekday in
            the schedule: charging to 80% needs materially less time than to 100%,
            so the deadline becomes critical later and the sun gets longer to do
            the work.
        charger_floor_current: the charger's real minimum (A). Only the AUTO
            deadline paths use it, and only as the floor under the current they
            work out from the energy still needed and the time left.

            This is not `charger_min_current` above, despite the name of that
            parameter: the caller passes NORMAL mode's base current there, which
            is correct for NORMAL and wrong here. Flooring a deadline
            calculation at NORMAL's base current throws the calculation away
            whenever the base is set high -- which is how a night that needed
            13 A spent itself at 23 A instead, finished hours early, and cycled
            the contactor eight times doing it. Defaults to `charger_min_current`
            when not given, which keeps old callers behaving as before.
    
    Returns:
        Tuple of (available_current_amps, debug_message)
    """
    grid_max_watts = grid_max_power * 1000  # Convert kW to W
    # See the argument's docstring: this must not fall back to NORMAL's base.
    floor_a = charger_floor_current if charger_floor_current is not None else charger_min_current
    
    # Calculate surplus available for EV after safety margin
    # surplus = PV - House - safety_margin
    surplus_available = surplus - safety_margin_watts
    
    # Handle AUTO and AUTO-ECO modes
    if mode in ["auto", "auto-eco"]:
        # First check if EV SOC data is missing (unknown EV state)
        # If so, use fallback mode with default capacity estimate
        if ev_soc is None or ev_battery_capacity_kwh is None:
            # Use default capacity and assume 50% SOC for time calculation
            fallback_capacity = 45.0
            fallback_soc = 50.0
            
            # Only proceed if target schedule exists
            if seconds_until_auto_target is None:
                # No schedule AND no EV data - can't make decision
                return 0.0, f"{mode.upper()}: No target schedule and no EV data, waiting for both"
            
            time_needed_hours = calculate_charge_time_hours(
                fallback_soc, target_soc, fallback_capacity,
                automatic_charge_current, voltage, battery_soc
            )
            time_until_target_hours = seconds_until_auto_target / 3600.0
            
            # Add 10 hours advance (no margin needed, fixed advance)
            advance_hours = 10.0
            time_with_advance = time_needed_hours + advance_hours
            
            if time_until_target_hours <= time_with_advance:
                # Time critical - charge at fixed 15A
                available_amps = automatic_charge_current
                return available_amps, f"{mode.upper()} FALLBACK: No EV data, within 10h advance ({time_until_target_hours:.1f}h left), charging at {automatic_charge_current}A"
            else:
                # Plenty of time - wait
                available_amps = 0.0
                return available_amps, f"{mode.upper()} FALLBACK: No EV data, still {time_until_target_hours:.1f}h left (need {time_with_advance:.1f}h with 10h advance), waiting"
        
        # EV SOC data is known. Check if target schedule exists.
        # If no schedule is set, cant determine when to charge - wait without charging
        if seconds_until_auto_target is None:
            return 0.0, f"{mode.upper()}: No target schedule defined, waiting (EV SOC known: {ev_soc:.0f}%)"
        
        # PHASE 1: AUTO charges immediately up to the phase-1 threshold
        # AUTO-ECO skips this and goes directly to solar-waiting logic
        if mode == "auto" and ev_soc < auto_phase1_soc_threshold:
            available_amps = automatic_charge_current
            time_hours = seconds_until_auto_target / 3600.0
            return available_amps, f"{mode.upper()} PHASE 1: EV SOC {ev_soc:.0f}% < {auto_phase1_soc_threshold:.0f}% threshold, charging at {automatic_charge_current}A (target in {time_hours:.1f}h)"
        
        # AUTO-ECO explicit check: if below 50%, skip PHASE 1 and wait for solar in PHASE 2
        if mode == "auto-eco" and ev_soc < auto_phase1_soc_threshold:
            # AUTO-ECO: no PHASE 1 charging even when scarica, go directly to PHASE 2
            _LOGGER.debug(f"AUTO-ECO: EV SOC {ev_soc:.0f}% < {auto_phase1_soc_threshold:.0f}% threshold, but skipping PHASE 1 (solar-only mode), proceeding to PHASE 2")
        
        # Calculate time needed at fixed 15A to charge from current SOC to the
        # target the deadline asks for (100% unless the schedule says otherwise).
        # Used by both AUTO and AUTO-ECO to determine if charging is critical
        time_until_target_hours = seconds_until_auto_target / 3600.0
        soc_to_charge = max(0.0, target_soc - ev_soc)
        
        # Always calculate time needed at 15A (not measured speed)
        # This gives both modes a common metric for deadline decisions
        time_needed_hours = calculate_charge_time_hours(
            ev_soc, target_soc, ev_battery_capacity_kwh, 
            automatic_charge_current, voltage, battery_soc
        )
        time_needed_with_margin = time_needed_hours * 1.10
        
        # One plan answers both halves of the deadline question -- when the grid
        # takes over, and at what current -- so that the two can no longer
        # disagree. See helpers.plan_grid_deadline.
        # The reference duration the plan is built on: charging losses and the
        # taper near a full pack, but not calculate_charge_time_hours' home-battery
        # fudge. That factor inflates the *car's* charge time because the *house*
        # battery is low -- a stand-in for "less power available" that the grid cap
        # now accounts for exactly, so counting it here would count it twice. It is
        # worth 16% at a 19% house battery, which is the difference between starting
        # at 22:00 and starting two hours early for nothing.
        plan_hours_at_reference = calculate_charge_time_hours(
            ev_soc, target_soc, ev_battery_capacity_kwh,
            automatic_charge_current, voltage, 100.0
        )
        plan_charge_now, plan_pace_a, plan_start_in_h, plan_why = plan_grid_deadline(
            hours_until_deadline=time_until_target_hours,
            energy_needed_kwh=ev_battery_capacity_kwh * (max(0.0, target_soc - ev_soc) / 100.0),
            voltage=voltage,
            reference_current=automatic_charge_current,
            charger_min_current=floor_a,
            charger_max_current=charger_max_current,
            now_hour=now_hour,
            band_start_hour=band_start_hour,
            band_end_hour=band_end_hour,
            hours_at_reference=plan_hours_at_reference,
        )

        if mode == "auto":
            # AUTO PHASE 1: below the threshold, charge at the base current
            if ev_soc < auto_phase1_soc_threshold:
                available_amps = automatic_charge_current
                return available_amps, f"{mode.upper()} PHASE 1: EV SOC {ev_soc:.0f}% < {auto_phase1_soc_threshold:.0f}%, charging at {automatic_charge_current}A to build buffer"
            
            # AUTO PHASE 2: Prefer solar, but use grid if deadline is critical
            excess_after_battery = calculate_excess_after_battery(surplus, battery_power, battery_soc, actual_battery_charge_w)
            
            if plan_charge_now:
                # CRITICAL: Not enough time at 15A, must start charging now
                # Strategy: Use solar + grid hybrid, with dynamic current adjustment based on measured charging speed
                
                # The pace comes from the plan: remaining energy over remaining
                # time, margin included. It replaces a guess built on the
                # measured charge speed, which needed a corruption check because
                # a stale reading could demand 48A.
                target_amps = plan_pace_a

                # Now apply the calculated target amperage using hybrid solar+grid approach
                if excess_after_battery > 0:
                    # Calculate how much current we can get from solar
                    solar_amps = power_to_current(excess_after_battery, voltage)
                    # Calculate how much grid current is needed to reach target amps
                    # But respect grid_max_power limit and house consumption (like Power mode does)
                    available_grid_watts = max(0, grid_max_watts - house_consumption - safety_margin_watts + (battery_power or 0))
                    grid_amps_max = power_to_current(available_grid_watts, voltage)
                    grid_amps_needed = max(0, target_amps - solar_amps)
                    # Clamp to grid limit
                    grid_amps_needed = min(grid_amps_needed, grid_amps_max)
                    # Total current: solar + grid, capped at charger max
                    available_amps = min(solar_amps + grid_amps_needed, charger_max_current)
                    
                    speed_info = ""
                    if ev_charging_speed_percent_per_hour > 0:
                        speed_info = f", speed {ev_charging_speed_percent_per_hour:.1f}%/h"
                    
                    return available_amps, f"{mode.upper()} PHASE 2: CRITICAL ({time_until_target_hours:.1f}h left, need {time_needed_hours:.1f}h at baseline 15A +10% margin{speed_info}), target {target_amps:.1f}A using {solar_amps:.1f}A solar + {grid_amps_needed:.1f}A grid (max {grid_amps_max:.1f}A) = {available_amps:.1f}A"
                else:
                    # No solar at all, use calculated target amps from grid, respecting grid limit
                    available_grid_watts = max(0, grid_max_watts - house_consumption - safety_margin_watts + (battery_power or 0))
                    grid_amps_max = power_to_current(available_grid_watts, voltage)
                    available_amps = min(target_amps, grid_amps_max)
                    
                    speed_info = ""
                    if ev_charging_speed_percent_per_hour > 0:
                        speed_info = f", speed {ev_charging_speed_percent_per_hour:.1f}%/h"
                    
                    return available_amps, f"{mode.upper()} PHASE 2: CRITICAL ({time_until_target_hours:.1f}h left, need {time_needed_hours:.1f}h at baseline 15A +10% margin{speed_info}), using grid at {available_amps:.1f}A (max {grid_amps_max:.1f}A available)"
            else:
                # NOT CRITICAL: Plenty of time, wait for solar excess
                available_amps = 0.0
                # What the plan is actually waiting for, instead of a second
                # estimate that could contradict it on screen.
                hours_until_charge_needed = plan_start_in_h if plan_start_in_h is not None else 0.0
                if excess_after_battery >= charger_min_current * voltage:
                    # Solar excess available (battery has taken its share)
                    available_amps = power_to_current(excess_after_battery, voltage)
                    available_amps = min(available_amps, charger_max_current)
                    return available_amps, f"{mode.upper()} PHASE 2: Charging now at {available_amps}A from solar. Target in {time_until_target_hours:.1f}h (will reach 100% in {time_needed_hours:.1f}h)"
                else:
                    # NOT CRITICAL: Insufficient excess - let timer manage hold_6a hysteresis
                    if auto_timer_active and auto_last_state == "hold_6a":
                        # Timer already active and holding: maintain 6A
                        return charger_min_current, f"{mode.upper()} PHASE 2: Timer holding 6A from battery (target in {time_until_target_hours:.1f}h, charge time at 15A: {time_needed_hours:.1f}h)"
                    elif auto_last_state == "solar_charging":
                        # Just transitioned from solar to insufficient: return min current for 1 cycle
                        # to let timer detect this and activate hold_6a in next evaluation
                        return charger_min_current, f"{mode.upper()} PHASE 2: Solar insufficient ({excess_after_battery:.0f}W < {charger_min_current * voltage:.0f}W needed), keeping {charger_min_current}A for timer to engage. Target in {time_until_target_hours:.1f}h, {plan_why}"
                    else:
                        # State is unknown or "waiting_for_solar" - return 0
                        if surplus > 0 and (battery_power or 0) > 0:
                            if battery_soc < 98:
                                # Battery reduction was applied (not full)
                                reduced_battery = min(battery_power, 1500)
                                return 0.0, f"{mode.upper()} PHASE 2: Waiting ({time_until_target_hours:.1f}h until target, {plan_why}). No excess (battery priority: {surplus:.0f}W - {reduced_battery:.0f}W battery = {excess_after_battery:.0f}W, need {charger_min_current * voltage:.0f}W)"
                            else:
                                # Battery is full, no reduction applied
                                return 0.0, f"{mode.upper()} PHASE 2: Waiting ({time_until_target_hours:.1f}h until target, {plan_why}). No excess (battery FULL: {surplus:.0f}W - {battery_power:.0f}W = {excess_after_battery:.0f}W, need {charger_min_current * voltage:.0f}W)"
                        else:
                            return 0.0, f"{mode.upper()} PHASE 2: Waiting ({time_until_target_hours:.1f}h until target, {plan_why}). Insufficient power (surplus {surplus}W - battery {battery_power or 0}W = {excess_after_battery}W, need {charger_min_current * voltage:.0f}W)"
        
        else:  # auto-eco
            # AUTO-ECO: Skip Phase 1 entirely, go directly to solar-first Phase 2
            # Will start earlier than AUTO if no sun (takes longer from lower SOC)
            
            # AUTO-ECO PHASE 2: Same deadline logic as AUTO, but solar-first
            excess_after_battery = calculate_excess_after_battery(surplus, battery_power, battery_soc, actual_battery_charge_w)
            
            if plan_charge_now:
                # CRITICAL: Not enough time at 15A, must start charging now
                # Strategy: Use solar + grid hybrid, with dynamic current adjustment based on measured charging speed
                
                # The pace comes from the plan: remaining energy over remaining
                # time, margin included. It replaces a guess built on the
                # measured charge speed, which needed a corruption check because
                # a stale reading could demand 48A.
                target_amps = plan_pace_a

                # Now apply the calculated target amperage using hybrid solar+grid approach
                if excess_after_battery > 0:
                    # Calculate how much current we can get from solar
                    solar_amps = power_to_current(excess_after_battery, voltage)
                    # Calculate how much grid current is needed to reach target amps
                    # But respect grid_max_power limit and house consumption (like Power mode does)
                    available_grid_watts = max(0, grid_max_watts - house_consumption - safety_margin_watts + (battery_power or 0))
                    grid_amps_max = power_to_current(available_grid_watts, voltage)
                    grid_amps_needed = max(0, target_amps - solar_amps)
                    # Clamp to grid limit
                    grid_amps_needed = min(grid_amps_needed, grid_amps_max)
                    # Total current: solar + grid, capped at charger max
                    available_amps = min(solar_amps + grid_amps_needed, charger_max_current)
                    
                    speed_info = ""
                    if ev_charging_speed_percent_per_hour > 0:
                        speed_info = f", speed {ev_charging_speed_percent_per_hour:.1f}%/h"
                    
                    return available_amps, f"{mode.upper()} PHASE 2: CRITICAL ({time_until_target_hours:.1f}h left, need {time_needed_hours:.1f}h at baseline 15A +10% margin{speed_info}), target {target_amps:.1f}A using {solar_amps:.1f}A solar + {grid_amps_needed:.1f}A grid (max {grid_amps_max:.1f}A) = {available_amps:.1f}A"
                else:
                    # No solar at all, use calculated target amps from grid, respecting grid limit
                    available_grid_watts = max(0, grid_max_watts - house_consumption - safety_margin_watts + (battery_power or 0))
                    grid_amps_max = power_to_current(available_grid_watts, voltage)
                    available_amps = min(target_amps, grid_amps_max)
                    
                    speed_info = ""
                    if ev_charging_speed_percent_per_hour > 0:
                        speed_info = f", speed {ev_charging_speed_percent_per_hour:.1f}%/h"
                    
                    return available_amps, f"{mode.upper()} PHASE 2: CRITICAL ({time_until_target_hours:.1f}h left, need {time_needed_hours:.1f}h at baseline 15A +10% margin{speed_info}), using grid at {available_amps:.1f}A (max {grid_amps_max:.1f}A available)"
            else:
                # NOT CRITICAL: Plenty of time, wait for solar excess
                available_amps = 0.0
                if excess_after_battery >= charger_min_current * voltage:
                    # Solar excess available (battery has taken its share)
                    available_amps = power_to_current(excess_after_battery, voltage)
                    available_amps = min(available_amps, charger_max_current)
                    return available_amps, f"{mode.upper()} PHASE 2: Waiting ({time_until_target_hours:.1f}h > {time_needed_hours:.1f}h needed), excess {excess_after_battery}W available → {available_amps}A"
                else:
                    # NOT CRITICAL: Insufficient excess - let timer manage hold_6a hysteresis
                    # IMPORTANT: When surplus just became insufficient, maintain charger_min_current for 1 cycle
                    # to allow the timer (applied next in coordinator) a chance to activate hold_6a state.
                    # Once timer updates state to "hold_6a", subsequent cycles will maintain it via timer.
                    # What the plan is actually waiting for, instead of a
                    # second estimate that could contradict it on screen.
                    hours_until_charge_needed = plan_start_in_h if plan_start_in_h is not None else 0.0
                    if auto_timer_active and auto_last_state == "hold_6a":
                        # Timer is holding 6A from battery to avoid stacca-attacca
                        return charger_min_current, f"{mode.upper()} PHASE 2: Timer holding 6A from battery (target in {time_until_target_hours:.1f}h, charge time at 15A: {time_needed_hours:.1f}h)"

                    elif auto_last_state == "solar_charging":
                        # Just transitioned from solar to insufficient: return min current for 1 cycle
                        # to let timer detect this and activate hold_6a in next evaluation
                        return charger_min_current, f"{mode.upper()} PHASE 2: Solar insufficient ({excess_after_battery:.0f}W < {charger_min_current * voltage:.0f}W needed), keeping {charger_min_current}A for timer to engage. Target in {time_until_target_hours:.1f}h, {plan_why}"
                    else:
                        # State is unknown or "waiting_for_solar" - return 0
                        if surplus > 0 and (battery_power or 0) > 0:
                            if battery_soc < 98:
                                # Battery reduction was applied (not full)
                                reduced_battery = min(battery_power, 1500)
                                return 0.0, f"{mode.upper()} PHASE 2: Waiting ({time_until_target_hours:.1f}h until target, {plan_why}). No excess (battery priority: {surplus:.0f}W - {reduced_battery:.0f}W battery = {excess_after_battery:.0f}W, need {charger_min_current * voltage:.0f}W)"
                            else:
                                # Battery is full, no reduction applied
                                return 0.0, f"{mode.upper()} PHASE 2: Waiting ({time_until_target_hours:.1f}h until target, {plan_why}). No excess (battery FULL: {surplus:.0f}W - {battery_power:.0f}W = {excess_after_battery:.0f}W, need {charger_min_current * voltage:.0f}W)"
                        else:
                            return 0.0, f"{mode.upper()} PHASE 2: Waiting ({time_until_target_hours:.1f}h until target, {plan_why}). Insufficient power (surplus {surplus}W - battery {battery_power or 0}W = {excess_after_battery}W, need {charger_min_current * voltage:.0f}W)"
    
    if mode == "eco":
        # ECO mode: Only charge from solar when:
        # 1. Surplus >= min required AND
        # 2. Battery SOC >= battery_start_charge_soc (protect low battery)
        if battery_soc < battery_start_charge_soc:
            available_amps = 0.0
            reason = f"Eco: SOC {battery_soc}% < start threshold {battery_start_charge_soc}%, waiting for battery to charge"
        elif surplus < charger_min_current * voltage:
            available_amps = 0.0
            reason = f"Surplus {surplus}W < min required {charger_min_current * voltage}W"
        else:
            available_amps = power_to_current(surplus, voltage)
            available_amps = min(available_amps, charger_max_current)
            reason = f"Eco mode: surplus {surplus}W -> {available_amps}A (SOC {battery_soc}% >= {battery_start_charge_soc}%)"
    
    elif mode == "normal":
        # Use the maximum between: min_current (from grid) or surplus (from solar)
        # If surplus is high (sunny) -> charge for free with solar
        # If surplus is low/negative (sunset) -> use min_current from grid
        
        # Reserve power for battery if SOC < 95%
        effective_surplus = surplus
        reservation_msg = ""
        
        if battery_soc < 95.0:
            effective_surplus = max(0, surplus - battery_reservation_power)
            reservation_msg = f" (Reserved {battery_reservation_power}W for battery)"
            
        surplus_current = power_to_current(max(0, effective_surplus), voltage)
        available_amps = max(charger_min_current, surplus_current)
        available_amps = min(available_amps, charger_max_current)
        reason = f"Normal mode: max(min {charger_min_current}A, surplus {surplus_current}A) = {available_amps}A{reservation_msg}"
    
    elif mode == "power":
        # Maximum: battery + surplus + grid (respecting grid limit with safety margin)
        # Grid capacity = (contract_A × voltage_V) - house_consumption - battery_discharge - safety_margin
        available_power = 0
        components = []
        
        # Add battery power only if SOC is above minimum threshold
        if battery_soc > battery_min_soc:
            available_power += battery_power
            components.append(f"Battery {power_to_current_float(battery_power, voltage):.1f}A")
        
        # Add surplus
        available_power += max(0, surplus)
        components.append(f"Surplus {power_to_current_float(max(0, surplus), voltage):.1f}A")
        
        # Add grid up to limit, accounting for house consumption, safety margin, and battery available
        # Available grid = (contract_A × voltage_V) - house_consumption - safety_margin + battery_available
        available_grid_watts = max(0, grid_max_watts - house_consumption - safety_margin_watts + (battery_power or 0))
        if available_grid_watts > 0:
            available_power += available_grid_watts
            components.append(f"Grid {power_to_current_float(available_grid_watts, voltage):.1f}A")
        
        available_amps = power_to_current(available_power, voltage)
        available_amps = min(available_amps, charger_max_current)
        reason = f"Power mode: {' + '.join(components)} = {available_amps}A (max {charger_max_current}A, SOC={battery_soc:.0f}%, House={house_consumption:.0f}W)"
    
    else:
        available_amps = 0.0
        reason = f"Unknown mode: {mode}"
    
    _LOGGER.debug(reason)
    return available_amps, reason


# -- Time-of-use tariff ----------------------------------------------------
# A charge that must happen tonight anyway may as well happen when the kWh is
# cheap. The band is a wall-clock window, usually crossing midnight, and it is
# the only thing in this module that knows about money.
#
# It never overrides the deadline: the window is consulted to decide *when* to
# start, and if the energy does not fit inside it the charge starts before it
# opens and pays the difference. A missed deadline costs a morning; a few kWh at
# the day rate costs small change.
CHEAP_BAND_START_HOUR = 22.0
CHEAP_BAND_END_HOUR = 7.0


def hours_until_band_open(
    now_hour: float, start_hour: float, end_hour: float
) -> float:
    """Hours until the cheap band opens, or 0.0 if it is open now.

    Hours are fractional, local, since midnight. A start later than the end means
    the band crosses midnight, which is the normal shape for a night rate.
    """
    if start_hour == end_hour:
        return 0.0  # degenerate: the whole day is cheap, so never wait
    if start_hour < end_hour:
        inside = start_hour <= now_hour < end_hour
    else:
        inside = now_hour >= start_hour or now_hour < end_hour
    if inside:
        return 0.0
    return (start_hour - now_hour) % 24.0


def plan_grid_deadline(
    hours_until_deadline: float,
    energy_needed_kwh: float,
    voltage: float,
    reference_current: float,
    charger_min_current: float,
    charger_max_current: float,
    now_hour: Optional[float] = None,
    band_start_hour: Optional[float] = None,
    band_end_hour: Optional[float] = None,
    pace_margin: float = 1.10,
    hours_at_reference: Optional[float] = None,
) -> Tuple[float, float, Optional[float], str]:
    """Decide when the grid takes over a deadline charge, and at what current.

    Two questions used to be answered in different places, by different rules,
    and the answers disagreed: the planner decided *whether* the deadline was
    urgent from a slack ratio, while only the deadline branch computed a current
    that actually met it. Between the moment the slack latch fired and the moment
    that branch opened, nobody raised the current and the car trickled at the
    charger minimum while the display claimed it was keeping pace.

    Both answers come from here, and the reference current is the axis:

      * **The cheap band alone can do it at the reference current or less.**
        Wait for the band, then charge at the pace the remaining window needs.
        Nothing is gained by starting sooner and paying the day rate.
      * **It cannot.** Then the overflow -- whatever the band cannot carry at the
        reference current -- has to be charged before the band opens, and the
        charge starts now. Spread over all the time left it asks the least
        current, often well under the reference; the same kWh lands at the same
        price either way, so the thinnest, gentlest version of that leg is the
        right one. When the band opens the pace is recomputed and rises.
      * **The overflow is too small to charge at all**, needing less than the
        charger's minimum: then waiting is cheaper than running the charger at
        its floor, and the band makes it up slightly above the reference.

    The pace is recomputed every cycle, so falling behind raises it and the
    margin is spent rather than banked. It is never the reference current for its
    own sake: finishing hours early buys nothing, and on a small supply the lower
    current is what keeps the charge clear of the contract limit.

    With no band configured the rule is the original one: start as late as the
    reference current allows, and pace to the deadline.

    Args:
        energy_needed_kwh: battery-side; charging losses are applied here.
        reference_current: the comfortable rate the band's capacity is measured
            against -- a yardstick, not a floor and not a ceiling.
        hours_at_reference: how long the charge takes at `reference_current`,
            from `calculate_charge_time_hours`. Pass it: that model knows about
            charging losses and the taper near a full pack, and dividing energy
            by power here instead would make the plan optimistic by the one
            margin it cannot afford to be optimistic about -- it would start too
            late. Falls back to the plain division when absent.

    Returns:
        (charge_now, pace_amps, hours_until_start, reason). `pace_amps` is the
        current to command when starting -- now if `charge_now`, otherwise at
        `hours_until_start` -- so a caller can say what it is waiting to do.
    """
    if energy_needed_kwh <= 0.0:
        return False, 0.0, None, "obiettivo già raggiunto"
    if voltage <= 0 or reference_current <= 0:
        return True, charger_max_current, 0.0, (
            "dati elettrici non validi, carico al massimo"
        )

    wall_kwh = energy_needed_kwh / CHARGING_EFFICIENCY
    kw_per_amp = voltage / 1000.0

    # The one duration everything else is measured against.
    h_ref = hours_at_reference
    if h_ref is None or h_ref <= 0.0:
        h_ref = wall_kwh / (reference_current * kw_per_amp)
    h_ref_safe = h_ref * pace_margin

    def amps_over(hours: float) -> float:
        """The current that finishes the charge in `hours`, with margin.

        Scaled from the reference rather than recomputed from energy, so it
        inherits whatever `hours_at_reference` knows about losses and taper.
        """
        if hours <= 0.0:
            return charger_max_current
        amps = reference_current * h_ref_safe / hours
        return max(charger_min_current, min(amps, charger_max_current))

    band_wait = None
    if (
        band_start_hour is not None
        and band_end_hour is not None
        and now_hour is not None
    ):
        band_wait = hours_until_band_open(now_hour, band_start_hour, band_end_hour)
        # A band that opens at or after the deadline cannot help this charge, and
        # pretending otherwise is worse than ignoring it: the plan would hold the
        # expensive leg down to the reference current and promise to make up the
        # rest "from 22:00", which is after the car was supposed to be ready.
        if band_wait >= hours_until_deadline:
            band_wait = None

    # -- No tariff band, or none that arrives in time ------------------------
    if band_wait is None:
        start_in = hours_until_deadline - h_ref_safe
        if start_in <= 0.0:
            pace = amps_over(hours_until_deadline)
            return True, pace, 0.0, f"passo {pace:.0f}A per arrivare in orario"
        pace = amps_over(hours_until_deadline - start_in)
        return False, pace, start_in, (
            f"posso partire fra {start_in:.1f}h a {pace:.0f}A e arrivare in orario"
        )

    # -- The band is open: pace what is left ---------------------------------
    if band_wait <= 0.0:
        horizon = hours_until_deadline
        hours_to_close = (band_end_hour - now_hour) % 24.0
        # Finishing inside the band is worth a little more current, but only when
        # the band can carry the whole charge at the reference rate. Otherwise
        # the deadline is the honest horizon.
        if 0.0 < hours_to_close < horizon and h_ref_safe <= hours_to_close:
            horizon = hours_to_close
        pace = amps_over(horizon)
        return True, pace, 0.0, f"fascia economica aperta, passo {pace:.0f}A"

    # -- The band is still to come ------------------------------------------
    band_hours = max(0.0, hours_until_deadline - band_wait)

    # Can the band carry the whole charge at the reference current? The margin is
    # on this side of the comparison, so the "band is enough" case really does
    # stay at or below the reference instead of asking for 10% more than it.
    if h_ref_safe <= band_hours:
        pace = amps_over(band_hours)
        return False, pace, band_wait, (
            f"aspetto la fascia economica fra {band_wait:.1f}h: "
            f"da allora {pace:.0f}A bastano per la scadenza"
        )

    # The hours of charging the band cannot absorb, and the current that fits
    # them into the time left before it opens.
    deficit_h = h_ref_safe - band_hours
    pre_amps = reference_current * deficit_h / band_wait

    if pre_amps < charger_min_current:
        # Less than the charger can even deliver. Running it at its floor would
        # buy day-rate energy to save a trickle; the band takes the difference.
        pace = amps_over(band_hours)
        return False, pace, band_wait, (
            f"aspetto la fascia economica fra {band_wait:.1f}h: manca poco, "
            f"meglio {pace:.0f}A in fascia che {charger_min_current:.0f}A adesso"
        )

    # Capped at the reference current: the leg before the band is the expensive
    # one, so it carries no more than the baseline and the band -- which may
    # then run above it -- takes the rest. Cheaper, and it is what makes the
    # baseline a baseline rather than a target.
    pre_amps = min(pre_amps, reference_current, charger_max_current)
    return True, pre_amps, 0.0, (
        f"{pre_amps:.0f}A adesso: la fascia da sola non basta, mi porto avanti "
        f"{deficit_h:.1f}h di carica e dalle {band_start_hour:.0f} salgo"
    )


def is_charger_connected(charger_status: Optional[str]) -> bool:
    """Check if EV charger is connected."""
    if charger_status is None:
        return False
    return charger_status.lower() in ["connected", "charging", "on"]


def apply_eco_timer(
    surplus: float,
    battery_soc: float,
    battery_start_charge_soc: float,
    charger_min_current: float,
    voltage: float,
    eco_timer_seconds: int,
    eco_last_state: Optional[str],
    eco_timer_active: bool,
    refresh_rate: int = 20,
    smart_solar_protection: bool = False,
    pv_power: float = 0.0,
) -> Tuple[float, int, Optional[str], bool, str]:
    """
    Apply ECO mode timer logic with 10-minute hysteresis.
    
    When solar drops below min requirement:
    - Hold 6A from battery for up to 10 minutes
    - If solar returns, reset timer and switch back to solar
    
    When solar rises above min requirement:
    - Wait 10 minutes before ramping up (avoid false positives from clouds)
    
    Args:
        surplus: Current surplus power (W)
        battery_soc: Current battery SOC (%)
        battery_start_charge_soc: SOC to start using battery (%)
        charger_min_current: Minimum charging current (A)
        voltage: Voltage (V)
        eco_timer_seconds: Current timer value (seconds)
        eco_last_state: Last state ("hold_6a" or "waiting_for_solar")
        eco_timer_active: Is timer currently active?
        refresh_rate: Update frequency in seconds (default 20)
    
    Returns:
        Tuple of (adjusted_current_A, new_timer_seconds, new_last_state, new_timer_active, debug_msg)
    """
    min_watts_required = charger_min_current * voltage
    eco_timer_max = 600  # 10 minutes in seconds
    
    surplus_sufficient = surplus >= min_watts_required
    
    # Case 1: Surplus is sufficient
    if surplus_sufficient:
        if eco_last_state in ["hold_6a", "smart_hold_6a"]:
            # Solar/surplus returned after hold_6a: ramp up immediately (no hysteresis needed after discarding)
            # User was just interrupted by temporary load (caffè, scaldabagno, etc)
            # When surplus returns, resume charging immediately without waiting
            if battery_soc < battery_start_charge_soc:
                msg = f"Eco: SOC {battery_soc}% < start threshold {battery_start_charge_soc}%, stop charging"
                return 0.0, 0, "stopped", False, msg
            available_amps = power_to_current(surplus, voltage)
            eco_timer_active = False
            msg = f"Eco: Surplus returned after hold_6a, ramping to {available_amps}A immediately (temp load cleared)"
            return available_amps, 0, "solar_charging", eco_timer_active, msg
        
        elif eco_last_state == "waiting_for_solar" and eco_timer_active:
            # Waiting period: check if sufficient current available to skip timer
            # If surplus is now sufficient (>= 6A), interrupt timer immediately
            if surplus_sufficient:
                # Sufficient current available NOW - interrupt timer immediately!
                available_amps = power_to_current(surplus, voltage)
                eco_timer_active = False
                msg = f"Eco: Sufficient solar detected ({surplus}W), skipping wait timer, ramping to {available_amps}A immediately"
                return available_amps, 0, eco_last_state, eco_timer_active, msg
            
            # Insufficient current - continue timer countdown
            eco_timer_seconds += refresh_rate
            if eco_timer_seconds >= eco_timer_max:
                # Timer expired, ramp up to full solar
                available_amps = power_to_current(surplus, voltage)
                eco_timer_active = False
                msg = f"Eco: Ramping up to {available_amps}A after 10min wait"
                return available_amps, 0, eco_last_state, eco_timer_active, msg
            else:
                time_left = eco_timer_max - eco_timer_seconds
                msg = f"Eco: Holding 6A, solar wait timer {time_left}s remaining"
                return charger_min_current, eco_timer_seconds, eco_last_state, eco_timer_active, msg
        
        else:
            # Normal solar charging (no timer active)
            # Check battery SOC before allowing charge
            if battery_soc < battery_start_charge_soc:
                msg = f"Eco: SOC {battery_soc}% < start threshold {battery_start_charge_soc}%, stop charging"
                return 0.0, 0, "stopped", False, msg
            available_amps = power_to_current(surplus, voltage)
            return available_amps, 0, "solar_charging", False, f"Eco: {available_amps}A from solar (SOC {battery_soc}% >= {battery_start_charge_soc}%)"
    
    # Case 2: Surplus is insufficient
    else:
        # Battery SOC check always takes priority (even over smart protection)
        if battery_soc <= battery_start_charge_soc:
            eco_timer_active = False
            msg = f"Eco: No solar and SOC {battery_soc}% <= {battery_start_charge_soc}%, stop charging"
            return 0.0, 0, "stopped", False, msg

        # Smart Solar Protection: if PV is producing but house consumed the surplus,
        # enter smart hold IMMEDIATELY - don't wait for the 10-min timer.
        # Root problem: the timer resets every time surplus briefly spikes above threshold,
        # so the 10-min expiry is never reached. Checking here ensures protection activates
        # as soon as PV is active, regardless of timer state.
        if smart_solar_protection and pv_power >= min_watts_required:
            msg = f"Eco: Smart hold - PV {pv_power:.0f}W active, house consuming surplus ({surplus:.0f}W). Holding {charger_min_current}A (anti-cycle BYD)"
            return charger_min_current, 0, "smart_hold_6a", True, msg

        # Regular flow: no smart protection or PV below threshold
        if eco_last_state == "solar_charging":
            # Just lost solar -> start hold timer
            eco_timer_seconds = 0
            eco_last_state = "hold_6a"
            eco_timer_active = True
            msg = "Eco: Solar lost, holding 6A from battery for 10min"
            return charger_min_current, eco_timer_seconds, eco_last_state, eco_timer_active, msg

        elif eco_last_state == "hold_6a" and eco_timer_active:
            # Still holding 6A, counting down
            eco_timer_seconds += refresh_rate
            if eco_timer_seconds >= eco_timer_max:
                eco_timer_active = False
                msg = "Eco: 10min hold expired, stopping charge"
                return 0.0, 0, "stopped", False, msg
            else:
                time_left = eco_timer_max - eco_timer_seconds
                msg = f"Eco: Holding 6A from battery, {time_left}s remaining"
                return charger_min_current, eco_timer_seconds, eco_last_state, eco_timer_active, msg

        elif eco_last_state == "smart_hold_6a":
            # PV dropped below threshold (otherwise smart protection branch above would have caught it)
            msg = f"Eco: PV dropped to {pv_power:.0f}W (< {min_watts_required:.0f}W threshold), stopping charge"
            return 0.0, 0, "stopped", False, msg

        elif eco_last_state == "waiting_for_solar":
            eco_timer_seconds = 0
            eco_last_state = "hold_6a"
            eco_timer_active = True
            msg = "Eco: No solar returned, holding 6A from battery"
            return charger_min_current, eco_timer_seconds, eco_last_state, eco_timer_active, msg

        else:
            eco_timer_active = False
            msg = "Eco: Insufficient surplus, stopping"
            return 0.0, 0, "stopped", False, msg


def apply_auto_timer(
    surplus: float,
    excess_after_battery: float,
    charger_min_current: float,
    voltage: float,
    auto_timer_seconds: int,
    auto_last_state: Optional[str],
    auto_timer_active: bool,
    refresh_rate: int = 20,
    smart_solar_protection: bool = False,
    pv_power: float = 0.0,
) -> Tuple[float, int, Optional[str], bool, str]:
    """
    Apply AUTO/AUTO-ECO mode timer logic with 10-minute hysteresis.
    
    When solar drops below min requirement:
    - Hold 6A from battery for up to 10 minutes
    - If solar returns, reset timer and switch back to solar
    
    When solar rises above min requirement:
    - Wait 10 minutes before ramping up (avoid false positives from clouds)
    
    Args:
        surplus: Current surplus power (W)
        excess_after_battery: Excess after battery allocation (W)
        charger_min_current: Minimum charging current (A)
        voltage: Voltage (V)
        auto_timer_seconds: Current timer value (seconds)
        auto_last_state: Last state ("hold_6a" or "waiting_for_solar")
        auto_timer_active: Is timer currently active?
        refresh_rate: Update frequency in seconds (default 20)
    
    Returns:
        Tuple of (adjusted_current_A, new_timer_seconds, new_last_state, new_timer_active, debug_msg)
    """
    min_watts_required = charger_min_current * voltage
    auto_timer_max = 600  # 10 minutes in seconds
    
    excess_sufficient = excess_after_battery >= min_watts_required
    
    # Case 1: Excess is sufficient
    if excess_sufficient:
        if auto_last_state in ["hold_6a", "smart_hold_6a"]:
            # Solar/excess returned after hold_6a: ramp up immediately (no hysteresis needed after discarding)
            # User was just interrupted by temporary load (caffè, scaldabagno, etc)
            # When excess returns, resume charging immediately without waiting
            available_amps = power_to_current(excess_after_battery, voltage)
            auto_timer_active = False
            msg = f"Auto: Excess returned after hold_6a, ramping to {available_amps}A immediately (temp load cleared)"
            return available_amps, 0, "solar_charging", auto_timer_active, msg
        
        elif auto_last_state == "waiting_for_solar" and auto_timer_active:
            # Waiting period: check if sufficient current available to skip timer
            if excess_sufficient:
                # Sufficient current available NOW - interrupt timer immediately!
                available_amps = power_to_current(excess_after_battery, voltage)
                auto_timer_active = False
                msg = f"Auto: Sufficient solar detected ({excess_after_battery}W), skipping wait timer, ramping to {available_amps}A immediately"
                return available_amps, 0, auto_last_state, auto_timer_active, msg
            
            # Insufficient current - continue timer countdown
            auto_timer_seconds += refresh_rate
            if auto_timer_seconds >= auto_timer_max:
                # Timer expired, ramp up to full solar
                available_amps = power_to_current(excess_after_battery, voltage)
                auto_timer_active = False
                msg = f"Auto: Ramping up to {available_amps}A after 10min wait"
                return available_amps, 0, auto_last_state, auto_timer_active, msg
            else:
                time_left = auto_timer_max - auto_timer_seconds
                msg = f"Auto: Holding 6A, solar wait timer {time_left}s remaining"
                return charger_min_current, auto_timer_seconds, auto_last_state, auto_timer_active, msg
        
        else:
            # Normal solar charging (no timer active)
            available_amps = power_to_current(excess_after_battery, voltage)
            return available_amps, 0, "solar_charging", False, f"Auto: {available_amps}A from solar"
    
    # Case 2: Excess is insufficient
    else:
        # Smart Solar Protection: if PV is producing but house consumed the surplus,
        # enter smart hold IMMEDIATELY - don't wait for the 10-min timer.
        # Root problem: the timer resets every time surplus briefly spikes above threshold,
        # so the 10-min expiry is never reached. Checking here ensures protection activates
        # as soon as PV is active, regardless of timer state.
        if smart_solar_protection and pv_power >= min_watts_required:
            msg = f"Auto: Smart hold - PV {pv_power:.0f}W active, house consuming surplus ({excess_after_battery:.0f}W excess). Holding {charger_min_current}A (anti-cycle BYD)"
            return charger_min_current, 0, "smart_hold_6a", True, msg

        # Regular flow: no smart protection or PV below threshold
        if auto_last_state == "solar_charging":
            # Just lost solar -> start hold timer
            auto_timer_seconds = 0
            auto_last_state = "hold_6a"
            auto_timer_active = True
            msg = "Auto: Solar lost, holding 6A from battery for 10min"
            return charger_min_current, auto_timer_seconds, auto_last_state, auto_timer_active, msg

        elif auto_last_state == "hold_6a" and auto_timer_active:
            # Still holding 6A, counting down
            auto_timer_seconds += refresh_rate
            if auto_timer_seconds >= auto_timer_max:
                auto_timer_active = False
                msg = "Auto: 10min hold expired, stopping charge"
                return 0.0, 0, "stopped", False, msg
            else:
                time_left = auto_timer_max - auto_timer_seconds
                msg = f"Auto: Holding 6A from battery, {time_left}s remaining"
                return charger_min_current, auto_timer_seconds, auto_last_state, auto_timer_active, msg

        elif auto_last_state == "smart_hold_6a":
            # PV dropped below threshold (otherwise smart protection branch above would have caught it)
            msg = f"Auto: PV dropped to {pv_power:.0f}W (< {min_watts_required:.0f}W threshold), stopping charge"
            return 0.0, 0, "stopped", False, msg

        elif auto_last_state == "waiting_for_solar":
            auto_timer_seconds = 0
            auto_last_state = "hold_6a"
            auto_timer_active = True
            msg = "Auto: No solar returned, holding 6A from battery"
            return charger_min_current, auto_timer_seconds, auto_last_state, auto_timer_active, msg

        else:
            auto_timer_active = False
            msg = "Auto: Insufficient surplus, stopping"
            return 0.0, 0, "stopped", False, msg

def estimate_battery_capacity(
    ev_soc_current: float,
    ev_soc_previous: float,
    charging_power_kw: float,
    voltage: float,
    time_delta_seconds: int = 20,
    previous_capacity_kwh: Optional[float] = None,
) -> Optional[float]:
    """
    Estimate EV battery capacity based on SOC change and charging power.
    
    Formula: Capacity = (Charging Power in kW × Time in hours) / (Δ SOC %)
    
    Args:
        ev_soc_current: Current EV SOC (%)
        ev_soc_previous: Previous EV SOC (%)
        charging_power_kw: Current charging power (kW)
        voltage: Voltage (V) - for reference
        time_delta_seconds: Time between measurements (default 20s)
        previous_capacity_kwh: Previous capacity estimate (for averaging)
    
    Returns:
        Estimated capacity in kWh, or None if calculation is invalid
    """
    # SOC change (%)
    soc_delta = ev_soc_current - ev_soc_previous
    
    # Not charging or invalid data
    if charging_power_kw <= 0 or soc_delta <= 0:
        return previous_capacity_kwh  # Return previous estimate
    
    # Time in hours
    time_hours = time_delta_seconds / 3600.0
    
    # Capacity = Energy / SOC_percent
    # Energy = Power × Time
    energy_kwh = charging_power_kw * time_hours
    capacity = energy_kwh / (soc_delta / 100.0)
    
    # Sanity check: capacity should be between 10 kWh and 200 kWh
    if capacity < 10 or capacity > 200:
        _LOGGER.warning(f"Invalid capacity estimate: {capacity} kWh (power={charging_power_kw}kW, Δ SOC={soc_delta}%)")
        return previous_capacity_kwh
    
    # Average with previous estimate (moving average for stability)
    if previous_capacity_kwh:
        new_capacity = (previous_capacity_kwh + capacity) / 2.0
        _LOGGER.debug(f"Capacity updated: {previous_capacity_kwh:.1f} kWh → {new_capacity:.1f} kWh (new estimate: {capacity:.1f} kWh)")
        return new_capacity
    
    _LOGGER.debug(f"Initial capacity estimate: {capacity:.1f} kWh")
    return capacity


def calculate_charge_time_hours(
    soc_current: float,
    soc_target: float,
    battery_capacity_kwh: float,
    charge_current_amps: float,
    voltage: float,
    battery_soc: float = 100.0,
) -> float:
    """
    Calculate time needed to charge EV from current SOC to target SOC.
    Adds safety margin if home battery is not at 100% (reduces available power).
    
    Formula: Time = (Capacity × (SOC_target - SOC_current) / 100) / Power
    Where Power = Current × Voltage × safety_factor
    
    Args:
        soc_current: Current EV SOC (%)
        soc_target: Target EV SOC (%)
        battery_capacity_kwh: EV battery capacity (kWh)
        charge_current_amps: Charging current (A)
        voltage: Voltage (V)
        battery_soc: Home battery SOC (%), default 100%. If < 100%, adds safety margin.
    
    Returns:
        Time in hours
    """
    if battery_capacity_kwh <= 0 or charge_current_amps <= 0 or voltage <= 0:
        return 0.0
    
    soc_delta_percent = soc_target - soc_current
    if soc_delta_percent <= 0:
        return 0.0
    
    # Energy needed in kWh (spec energy that must enter the battery)
    energy_needed = battery_capacity_kwh * (soc_delta_percent / 100.0)

    # Wall power in kW at the given charge current
    power_kw = (charge_current_amps * voltage) / 1000.0

    # Charging efficiency (wall → battery): only a fraction of wall power reaches the battery.
    # Using CHARGING_EFFICIENCY constant (0.90 = 90%).
    efficiency_factor = 1.0 / CHARGING_EFFICIENCY  # > 1: need MORE wall-hours than battery-kWh

    # CC/CV taper: EVs reduce charging current near 100% SOC (BMS CV phase).
    # The last 5% can take as long as a much larger portion at full rate.
    # Add 20% overhead whenever the target is 95%+.
    taper_factor = 1.20 if soc_target >= 95 else 1.0

    # Home battery safety margin: if not at 100%, it contributes slightly less than its max.
    battery_margin = 1.0 + ((100.0 - battery_soc) * 0.002 if battery_soc < 100.0 else 0.0)

    # Combined factor
    combined_factor = efficiency_factor * taper_factor * battery_margin

    # Time in hours
    time_hours = energy_needed * combined_factor / power_kw if power_kw > 0 else 0.0

    _LOGGER.debug(
        f"Charge time: {battery_capacity_kwh:.1f}kWh × {soc_delta_percent:.1f}% "
        f"× {combined_factor:.3f} (eff={efficiency_factor:.2f}, taper={taper_factor:.2f}, bat_margin={battery_margin:.3f}) "
        f"/ {power_kw:.2f}kW = {time_hours:.2f}h"
    )
    
    return time_hours


def should_start_auto_charge(
    ev_soc: float,
    battery_capacity_kwh: Optional[float],
    charge_current_amps: float,
    voltage: float,
    seconds_until_target: int,
    automatic_charge_current: float,
    battery_soc: float = 100.0,
    target_soc: float = 100.0,
) -> Tuple[bool, str]:
    """
    Determine if AUTO mode should start charging based on time until target.
    
    Args:
        ev_soc: Current EV SOC (%)
        battery_capacity_kwh: Battery capacity (kWh)
        charge_current_amps: Current charge current (A)
        voltage: Voltage (V)
        seconds_until_target: Seconds remaining until target time
        automatic_charge_current: Configured AUTO charge current (A)
    
    Returns:
        Tuple of (should_charge, reason)
    """
    if not battery_capacity_kwh or battery_capacity_kwh <= 0:
        return False, "Battery capacity not estimated yet"
    
    # Calculate time needed to reach the scheduled target SOC
    time_needed_hours = calculate_charge_time_hours(
        ev_soc, target_soc, battery_capacity_kwh, automatic_charge_current, voltage, battery_soc
    )
    
    # Convert seconds to hours
    time_until_target_hours = seconds_until_target / 3600.0
    
    # Add 10 hours advance + 10% safety margin
    advance_hours = 10.0
    time_needed_with_advance = time_needed_hours + advance_hours
    
    should_charge = time_until_target_hours <= time_needed_with_advance
    
    reason = (
        f"Time remaining: {time_until_target_hours:.2f}h, Time needed: {time_needed_hours:.2f}h "
        f"(with 10h advance: {time_needed_with_advance:.2f}h) → {'START' if should_charge else 'WAIT'}"
    )
    
    return should_charge, reason


DEFAULT_TARGET_SOC = 100.0


def resolve_target_soc(soc_schedule: Optional[dict], day: str) -> float:
    """The SOC a given weekday's deadline asks for.

    Missing, blank or unparseable means 100: a schedule written before target SOC
    existed, or a day the user never touched, has to keep meaning "fill it up".
    """
    if not soc_schedule:
        return DEFAULT_TARGET_SOC
    raw = soc_schedule.get(day)
    if raw is None or raw == "":
        return DEFAULT_TARGET_SOC
    try:
        value = float(raw)
    except (TypeError, ValueError):
        return DEFAULT_TARGET_SOC
    if value <= 0:
        return DEFAULT_TARGET_SOC
    return min(100.0, value)


def get_next_target_time(
    target_schedule: dict,
    current_datetime,
    soc_schedule: Optional[dict] = None,
    ev_soc: Optional[float] = None,
) -> Tuple[Optional[int], Optional[str], float]:
    """
    Get the next target time based on current day/time and schedule.

    Args:
        target_schedule: Dict with keys "monday"-"sunday", each containing a time string "HH:MM" or None
        current_datetime: Current datetime object
        soc_schedule: Dict with the same keys holding the SOC (%) each deadline asks
            for. Absent or partial means 100% for the days it does not cover.
        ev_soc: Current EV SOC (%), used only to decide whether a deadline that has
            just passed still deserves the grace window below.

    Returns:
        Tuple of (seconds_until_target, target_time_str, target_soc).
        (None, None, 100.0) when no target applies.
    """
    if not target_schedule:
        return None, None, DEFAULT_TARGET_SOC

    from datetime import datetime, timedelta

    day_names = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"]
    current_weekday_name = day_names[current_datetime.weekday()]

    # Check if today has a target and it hasn't passed yet
    target_time_str = target_schedule.get(current_weekday_name)

    if target_time_str:
        target_soc = resolve_target_soc(soc_schedule, current_weekday_name)
        try:
            target_hour, target_minute = map(int, target_time_str.split(":"))
            target_datetime = current_datetime.replace(hour=target_hour, minute=target_minute, second=0, microsecond=0)

            if current_datetime <= target_datetime:
                # Target hasn't passed yet
                time_delta = target_datetime - current_datetime
                seconds_until_target = int(time_delta.total_seconds())
                return seconds_until_target, target_time_str, target_soc

            # Target just passed: stay in CRITICAL mode for a 30-minute grace window.
            # Without this, the system switches to "NOT CRITICAL" (next day's target is 24h away)
            # and stops charging even if the EV is at 99%.
            #
            # Only when the target was actually missed, though. A deadline asking for
            # 80% on a car already at 80% is satisfied, and forcing it critical here
            # would pull grid power at full tariff to charge a car that is done.
            elapsed_seconds = (current_datetime - target_datetime).total_seconds()
            target_met = ev_soc is not None and ev_soc >= target_soc - 0.5
            if elapsed_seconds <= 1800 and not target_met:  # 30 minutes
                return 60, target_time_str, target_soc  # 60 s = very critical -> charge at max amps to finish ASAP
            # More than 30 min past target, or target already met -> look for next day's target
        except (ValueError, AttributeError):
            pass

    # No target for today or it has passed - look for next target in future days
    for days_ahead in range(1, 8):  # Check next 7 days max
        future_date = current_datetime + timedelta(days=days_ahead)
        future_weekday_idx = future_date.weekday()
        future_weekday_name = day_names[future_weekday_idx]

        target_time_str = target_schedule.get(future_weekday_name)
        if target_time_str:
            # Found a target day
            try:
                target_hour, target_minute = map(int, target_time_str.split(":"))
                target_datetime = future_date.replace(hour=target_hour, minute=target_minute, second=0, microsecond=0)

                time_delta = target_datetime - current_datetime
                seconds_until_target = int(time_delta.total_seconds())
                return (
                    seconds_until_target,
                    target_time_str,
                    resolve_target_soc(soc_schedule, future_weekday_name),
                )
            except (ValueError, AttributeError):
                continue

    # No target found in next 7 days
    return None, None, DEFAULT_TARGET_SOC
